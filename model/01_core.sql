-- Добавляем категории из списка товаров.
INSERT INTO core.dim_category
    (category_name_pt, has_translation, is_unknown)
SELECT DISTINCT
    pg_temp.text_to_clean(product_category_name),
    false,
    false
FROM raw.products
WHERE pg_temp.text_to_clean(product_category_name) IS NOT NULL
  AND pg_temp.text_to_clean(product_category_name) <> 'unknown'
ON CONFLICT (category_name_pt) DO NOTHING;

-- Добавляем категории, которые есть только в таблице переводов.
INSERT INTO core.dim_category
    (category_name_pt, has_translation, is_unknown)
SELECT DISTINCT
    pg_temp.text_to_clean(product_category_name),
    false,
    false
FROM raw.product_category_translation
WHERE pg_temp.text_to_clean(product_category_name) IS NOT NULL
  AND pg_temp.text_to_clean(product_category_name) <> 'unknown'
ON CONFLICT (category_name_pt) DO NOTHING;

-- Есть строка в таблице переводов -> has_translation = true.
UPDATE core.dim_category c
SET has_translation = true
FROM raw.product_category_translation t
WHERE c.category_name_pt = pg_temp.text_to_clean(t.product_category_name);

-- Записываем английское название, если оно не пустое.
UPDATE core.dim_category c
SET category_name_en = pg_temp.text_to_clean(t.product_category_name_english)
FROM raw.product_category_translation t
WHERE c.category_name_pt = pg_temp.text_to_clean(t.product_category_name)
  AND pg_temp.text_to_clean(t.product_category_name_english) IS NOT NULL;

