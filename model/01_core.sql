DROP SCHEMA IF EXISTS core CASCADE;
CREATE SCHEMA core;

-- 1. Создание таблиц. Сначала справочники, затем факты.
CREATE TABLE core.dim_customer (
    customer_unique_id TEXT PRIMARY KEY,
    last_zip_code_prefix CHAR(5),
    last_city TEXT,
    last_state CHAR(2)
);

CREATE TABLE core.dim_seller (
	seller_id TEXT PRIMARY KEY,
	zip_code_prefix CHAR(5),
	city_raw TEXT,
	city TEXT,
	state CHAR(2)
);

CREATE TABLE core.dim_category (
    category_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name_pt TEXT NOT NULL UNIQUE,
    category_name_en TEXT,
    has_translation BOOLEAN NOT NULL,
    is_unknown BOOLEAN NOT NULL,

    CONSTRAINT chk_dim_category_unknown
        CHECK (is_unknown = (category_id = 0))
);
CREATE TABLE core.dim_order_status (status_code TEXT PRIMARY KEY,
    status_name_ru TEXT NOT NULL,
    stage_order SMALLINT NOT NULL,
    is_delivered BOOLEAN NOT NULL,
    is_cancelled BOOLEAN NOT NULL,
    is_final BOOLEAN NOT NULL,

    CONSTRAINT chk_order_status_stage
        CHECK (stage_order >= 0),

    CONSTRAINT chk_order_status_flags
        CHECK (
            (status_code = 'delivered' AND is_delivered AND is_final AND NOT is_cancelled)
            OR
            (status_code IN ('canceled', 'unavailable')
                AND is_cancelled AND is_final AND NOT is_delivered)
            OR
            (status_code IN ('created', 'approved', 'invoiced', 'processing', 'shipped')
                AND NOT is_delivered AND NOT is_cancelled AND NOT is_final)
        )
);
CREATE TABLE core.dim_payment_type (
    payment_type TEXT PRIMARY KEY,
    payment_type_name_ru TEXT NOT NULL,
    is_known BOOLEAN NOT NULL
);
CREATE TABLE core.dim_product (
    product_id TEXT PRIMARY KEY,
    category_id SMALLINT NOT NULL,
    name_length INTEGER,
    description_length INTEGER,
    photos_qty INTEGER,
    weight_g INTEGER,
    length_cm INTEGER,
    height_cm INTEGER,
    width_cm INTEGER,

    CONSTRAINT fk_dim_product_category
        FOREIGN KEY (category_id)
        REFERENCES core.dim_category (category_id)
);

CREATE TABLE core.fact_order (
    order_id TEXT PRIMARY KEY,

    customer_unique_id TEXT NOT NULL,
    source_customer_id TEXT NOT NULL UNIQUE,
    status_code TEXT NOT NULL,

    purchased_at TIMESTAMP NOT NULL,
    purchase_date DATE NOT NULL,
    approved_at TIMESTAMP,
    delivered_carrier_at TIMESTAMP,
    delivered_customer_at TIMESTAMP,
    estimated_delivery_date DATE,

    ship_zip_code_prefix CHAR(5),
    ship_city TEXT,
    ship_state CHAR(2),

    has_items BOOLEAN NOT NULL DEFAULT false,
    has_payment BOOLEAN NOT NULL DEFAULT false,

    dq_status_date_conflict BOOLEAN NOT NULL DEFAULT false,
    dq_carrier_before_purchase BOOLEAN NOT NULL DEFAULT false,

    CONSTRAINT fk_fact_order_customer
        FOREIGN KEY (customer_unique_id)
        REFERENCES core.dim_customer (customer_unique_id),

    CONSTRAINT fk_fact_order_status
        FOREIGN KEY (status_code)
        REFERENCES core.dim_order_status (status_code),

    CONSTRAINT chk_fact_order_purchase_date
        CHECK (purchase_date = purchased_at::DATE)
);
CREATE TABLE core.fact_order_item (
    order_id TEXT NOT NULL,
    order_item_id SMALLINT NOT NULL,
    product_id TEXT NOT NULL,
    seller_id TEXT NOT NULL,
    shipping_limit_at TIMESTAMP NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    freight_value NUMERIC(12, 2) NOT NULL,

    CONSTRAINT pk_fact_order_item
        PRIMARY KEY (order_id, order_item_id),

    CONSTRAINT fk_fact_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES core.fact_order (order_id),

    CONSTRAINT fk_fact_order_item_product
        FOREIGN KEY (product_id)
        REFERENCES core.dim_product (product_id),

    CONSTRAINT fk_fact_order_item_seller
        FOREIGN KEY (seller_id)
        REFERENCES core.dim_seller (seller_id)
);
CREATE TABLE core.fact_payment (
    order_id TEXT NOT NULL,
    payment_sequential SMALLINT NOT NULL,
    payment_type TEXT NOT NULL,
    installments SMALLINT NOT NULL,
    payment_value NUMERIC(12, 2) NOT NULL,

    CONSTRAINT pk_fact_payment
        PRIMARY KEY (order_id, payment_sequential),

    CONSTRAINT fk_fact_payment_order
        FOREIGN KEY (order_id)
        REFERENCES core.fact_order (order_id),

    CONSTRAINT fk_fact_payment_type
        FOREIGN KEY (payment_type)
        REFERENCES core.dim_payment_type (payment_type)
);
CREATE TABLE core.fact_review (
    review_id TEXT NOT NULL,
    order_id TEXT NOT NULL,
    review_score SMALLINT NOT NULL,
    comment_title TEXT,
    comment_message TEXT,
    created_date DATE NOT NULL,
    answered_at TIMESTAMP,

    CONSTRAINT pk_fact_review
        PRIMARY KEY (review_id, order_id),

    CONSTRAINT fk_fact_review_order
        FOREIGN KEY (order_id)
        REFERENCES core.fact_order (order_id),

    CONSTRAINT chk_fact_review_score
        CHECK (review_score BETWEEN 1 AND 5)
);


-- Функции

-- Убираем пробелы по краям. Пустая строка -> NULL.
CREATE OR REPLACE FUNCTION pg_temp.text_to_clean(text_value text)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    v_text text;
BEGIN
    v_text := btrim(text_value, E' \t\r\n');
    IF v_text = '' THEN RETURN NULL; END IF;
    RETURN v_text;
END;
$$;

-- Переводим текст в число. Пустая строка -> NULL.
CREATE OR REPLACE FUNCTION pg_temp.text_to_numeric(num_value text)
RETURNS numeric
LANGUAGE plpgsql
AS $$
DECLARE
    v_num text;
BEGIN
    v_num := btrim(num_value, E' \t\r\n');
    IF v_num = '' THEN RETURN NULL; END IF;
    RETURN v_num::numeric;
END;
$$;

-- Переводим текст в дату и время. Пустая строка -> NULL.
CREATE OR REPLACE FUNCTION pg_temp.text_to_timestamp(time_value text)
RETURNS timestamp without time zone
LANGUAGE plpgsql
AS $$
DECLARE
    v_time text;
BEGIN
    v_time := btrim(time_value, E' \t\r\n');
    IF v_time = '' THEN RETURN NULL; END IF;
    RETURN v_time::timestamp without time zone;
END;
$$;

-- Убираем из названия города продавца часть после /.
-- Если город состоит только из цифр, возвращаем NULL.
CREATE OR REPLACE FUNCTION pg_temp.text_to_city(city_value text)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    v_city text;
BEGIN
    v_city := pg_temp.text_to_clean(city_value);
    v_city := pg_temp.text_to_clean(split_part(v_city, '/', 1));
    IF v_city ~ '^[0-9]+$' THEN RETURN NULL; END IF;
    RETURN v_city;
END;
$$;

