-- Справочник покупатель

INSERT INTO core.dim_customer
    (customer_unique_id, last_zip_code_prefix, last_city, last_state)
SELECT DISTINCT ON (c.customer_unique_id)
    c.customer_unique_id,
    LPAD(pg_temp.text_to_clean(c.customer_zip_code_prefix), 5, '0'),
    pg_temp.text_to_clean(c.customer_city),
    UPPER(pg_temp.text_to_clean(c.customer_state))
FROM raw.customers c
LEFT JOIN raw.orders o
    ON o.customer_id = c.customer_id
ORDER BY
    c.customer_unique_id,
    pg_temp.text_to_timestamp(o.order_purchase_timestamp) DESC NULLS LAST,
    c.customer_id;

