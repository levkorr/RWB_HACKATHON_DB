    ON c.customer_id = o.customer_id;

-- Отмечаем, у каких заказов есть товары.
UPDATE core.fact_order o
SET has_items = true
FROM raw.order_items i
WHERE o.order_id = i.order_id;

-- Отмечаем, у каких заказов есть платежи.
UPDATE core.fact_order o
SET has_payment = true
FROM raw.order_payments p
WHERE o.order_id = p.order_id;

-- delivered без даты вручения или canceled с датой вручения.
UPDATE core.fact_order
SET dq_status_date_conflict =
    (status_code = 'delivered' AND delivered_customer_at IS NULL)
    OR (status_code = 'canceled' AND delivered_customer_at IS NOT NULL);

-- Передача перевозчику раньше покупки.
UPDATE core.fact_order
SET dq_carrier_before_purchase =
    COALESCE(delivered_carrier_at < purchased_at, false);

